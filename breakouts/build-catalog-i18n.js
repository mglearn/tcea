#!/usr/bin/env node
/* build-catalog-i18n.js — write i18n-catalog.js from _catalog/<lang>.json. */
const fs=require('fs'),path=require('path'),ROOT=__dirname,LANGS=['en','es','vi','ar','hi','ur','zh'];
const dict={};for(const l of LANGS){const fp=path.join(ROOT,'_catalog',l+'.json');if(fs.existsSync(fp))dict[l]=JSON.parse(fs.readFileSync(fp,'utf8'));}
fs.writeFileSync(path.join(ROOT,'i18n-catalog.js'),'/* Auto-generated by build-catalog-i18n.js — catalog page language dictionary. */\nBreakoutI18n.register("catalog", '+JSON.stringify(dict)+');\n');
console.log('build-catalog-i18n: langs ['+Object.keys(dict).join(', ')+']');
