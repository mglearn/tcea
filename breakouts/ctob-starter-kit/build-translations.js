#!/usr/bin/env node
/* build-translations.js — the breakout TRANSLATION ENGINE.
   Merges per-language translation files onto an English-only breakout to produce
   the multi-language `window.BREAKOUT` the runtime consumes.

     Reads:  <path>.en.js          English-only source: window.BREAKOUT with UI.en + CONTENT.en
             <dir>/_i18n/<lang>.json   translated TEXT only, same array order/count as English
     Writes: <path>.js             window.BREAKOUT with every available language merged in

   Only TEXT is translated. Every gameplay-critical field — id, ico, type, len,
   color, answerIndex, item order + `strong`, seq `pads[].k` + `answer` order,
   `digit` answer — is copied VERBATIM from English, so a translation can never
   corrupt gameplay. Word-lock answers become the translated variants PLUS the
   English fallback (so a student typing in either language succeeds).

   Missing languages are simply skipped — the runtime falls back to English per key.

   Usage:  node build-translations.js example/example      (pass the path WITHOUT .en.js)

   Translation file schema (one per language, e.g. _i18n/es.json):
     {
       "chrome": { "header.h1": "...", "ui.check": "...", ... same keys as UI.en ... },
       "clues":  [ {nm,title,body} x6 ],                        // same order as English
       "locks":  [ {title, q, reason,                            // same order as English
                    // ONE of, matching the lock's type:
                    "options":[..x3..] | "items":[..x4 strings..] | "pads":[..emoji labels..] | "word":[..answers..] }
                    x4 ]
     }
*/
const fs = require('fs');
const path = require('path');
const LANGS = ['es', 'vi', 'ar', 'hi', 'ur', 'zh'];

const arg = (process.argv[2] || 'example/example').replace(/\.en\.js$/, '');
const enFile = arg + '.en.js';
const outFile = arg + '.js';
const i18nDir = path.join(path.dirname(arg), '_i18n');

if (!fs.existsSync(enFile)) { console.error('English source not found: ' + enFile); process.exit(1); }

function evalGlobal(file) {
  const w = { window: {} };
  eval('(function(window){' + fs.readFileSync(file, 'utf8') + '})(w.window)');
  return w.window.BREAKOUT;
}
function readI18n(lang) {
  const fp = path.join(i18nDir, lang + '.json');
  return fs.existsSync(fp) ? JSON.parse(fs.readFileSync(fp, 'utf8')) : null;
}

// zip translated text onto an English clue/lock, keeping every gameplay field.
function zipClues(enClues, tClues) {
  return enClues.map((c, i) => {
    const t = (tClues && tClues[i]) || {};
    return Object.assign({}, c, { nm: t.nm ?? c.nm, title: t.title ?? c.title, body: t.body ?? c.body });
  });
}
function zipLocks(enLocks, tLocks) {
  return enLocks.map((l, i) => {
    const t = (tLocks && tLocks[i]) || {};
    const out = Object.assign({}, l, { title: t.title ?? l.title, q: t.q ?? l.q, reason: t.reason ?? l.reason });
    if (l.type === 'mc' && Array.isArray(t.options)) out.options = l.options.map((o, j) => t.options[j] ?? o);
    if (l.type === 'multi' && Array.isArray(t.items)) out.items = l.items.map((it, j) => Object.assign({}, it, { t: t.items[j] ?? it.t }));
    if (l.type === 'seq' && Array.isArray(t.pads)) out.pads = l.pads.map((p, j) => Object.assign({}, p, { e: t.pads[j] ?? p.e }));
    if (l.type === 'word') {
      const tw = Array.isArray(t.word) ? t.word : (typeof t.word === 'string' && t.word ? [t.word] : []);
      out.answer = [...new Set([...tw, ...l.answer])];   // translated variants + English fallback
    }
    return out;
  });
}

const B = evalGlobal(enFile);
if (!B || !B.UI || !B.UI.en || !B.CONTENT || !B.CONTENT.en) {
  console.error('Source must define window.BREAKOUT with UI.en and CONTENT.en'); process.exit(1);
}

const langsBuilt = ['en'];
for (const lang of LANGS) {
  const data = readI18n(lang);
  if (!data) continue;
  B.UI[lang] = Object.assign({}, B.UI.en, data.chrome || {});
  B.CONTENT[lang] = {
    clues: zipClues(B.CONTENT.en.clues, data.clues),
    locks: zipLocks(B.CONTENT.en.locks, data.locks),
  };
  langsBuilt.push(lang);
}

fs.writeFileSync(outFile,
  '/* Auto-generated by build-translations.js — do not edit by hand.\n' +
  '   Edit ' + path.basename(enFile) + ' (English) and _i18n/<lang>.json (translations), then rebuild. */\n' +
  'window.BREAKOUT = ' + JSON.stringify(B, null, 2) + ';\n');

console.log(path.basename(outFile) + ': languages [' + langsBuilt.join(', ') + ']');
