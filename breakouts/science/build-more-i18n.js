#!/usr/bin/env node
/* build-more-i18n.js — write each grade's i18n-more.js from _more/<lang>.json. */
const fs=require('fs'),path=require('path'),ROOT=__dirname,LANGS=['en','es','vi','ar','hi','ur','zh'];
const data={};for(const l of LANGS){const fp=path.join(ROOT,'_more',l+'.json');if(fs.existsSync(fp))data[l]=JSON.parse(fs.readFileSync(fp,'utf8'));}
const grades=Object.keys(data.en.grades);
for(const g of grades){const dict={};for(const l of LANGS){if(!data[l])continue;dict[l]=Object.assign({},data[l].shared||{},(data[l].grades&&data[l].grades[g])||{});}
fs.writeFileSync(path.join(ROOT,g,'i18n-more.js'),'/* Auto-generated by build-more-i18n.js */\nBreakoutI18n.register("science-'+g+'-more", '+JSON.stringify(dict)+');\n');}
console.log('build-more-i18n: '+grades.length+' files, langs ['+Object.keys(data).join(', ')+']');
