/* Gallery logic for the "Getting to Know You" worksheet collection.
   Reads window.GTKY_MANIFEST (generated by build-manifest.sh), renders cards
   filtered by the current i18n language + band/subject filters, and re-renders
   whenever the language switcher fires `breakout-i18n:changed`. */
(function () {
  'use strict';

  var M = window.GTKY_MANIFEST || [];
  var t = function (k, vars) { return window.BreakoutI18n.t(k, vars); };
  var langLabel = { en: 'English', es: 'Español', vi: 'Tiếng Việt' };

  // Canonical display order.
  var BAND_ORDER = ['k-2', '3-5', '6-8', '9-12'];
  var SUBJECT_ORDER = ['science', 'math', 'ela', 'social-studies', 'fine-arts'];
  var GRADE_ORDER = ['kindergarten', 'grade-1', 'grade-2', 'grade-3', 'grade-4', 'grade-5', '6-8', '9-12'];

  var state = { band: 'all', subject: 'all' };

  function uniqueSorted(values, order) {
    var seen = {};
    values.forEach(function (v) { seen[v] = true; });
    return order.filter(function (o) { return seen[o]; });
  }

  function buildFilter(selectEl, values, order, allLabelKey, current) {
    selectEl.innerHTML = '';
    var optAll = document.createElement('option');
    optAll.value = 'all';
    optAll.textContent = t(allLabelKey);
    selectEl.appendChild(optAll);
    uniqueSorted(values, order).forEach(function (v) {
      var o = document.createElement('option');
      o.value = v;
      selectEl.appendChild(o);
    });
    selectEl.value = current;
  }

  function refreshFilterLabels() {
    // (Re)label filter <option>s in the current language without losing selection.
    var bandSel = document.getElementById('filter-band');
    var subjSel = document.getElementById('filter-subject');
    Array.prototype.forEach.call(bandSel.options, function (o) {
      o.textContent = o.value === 'all' ? t('filter.all') : t('band.' + o.value);
    });
    Array.prototype.forEach.call(subjSel.options, function (o) {
      o.textContent = o.value === 'all' ? t('filter.all') : t('subject.' + o.value);
    });
  }

  function render() {
    var lang = window.BreakoutI18n.getLang();
    var grid = document.getElementById('gallery');
    var note = document.getElementById('gallery-note');
    var count = document.getElementById('gallery-count');
    var lname = langLabel[lang] || lang;

    var items = M.filter(function (w) {
      return w.lang === lang &&
        (state.band === 'all' || w.band === state.band) &&
        (state.subject === 'all' || w.subject === state.subject);
    });

    // Sort by band, then subject, then grade, then variant (base before v2, v3…).
    items.sort(function (a, b) {
      var d = BAND_ORDER.indexOf(a.band) - BAND_ORDER.indexOf(b.band);
      if (d) return d;
      d = SUBJECT_ORDER.indexOf(a.subject) - SUBJECT_ORDER.indexOf(b.subject);
      if (d) return d;
      d = GRADE_ORDER.indexOf(a.grade) - GRADE_ORDER.indexOf(b.grade);
      if (d) return d;
      return (a.variant || '').localeCompare(b.variant || '');
    });

    count.textContent = t('gallery.count', { n: items.length, lang: lname });
    note.textContent = t('gallery.langNote', { lang: lname });

    grid.innerHTML = '';
    if (!items.length) {
      var empty = document.createElement('p');
      empty.className = 'empty';
      empty.textContent = t('gallery.empty', { lang: lname });
      grid.appendChild(empty);
      return;
    }

    var lastGroup = null;
    items.forEach(function (w) {
      var groupKey = w.band + '|' + w.subject;
      if (groupKey !== lastGroup) {
        lastGroup = groupKey;
        var h = document.createElement('h3');
        h.className = 'group-head';
        h.textContent = t('band.' + w.band) + ' · ' + t('subject.' + w.subject);
        grid.appendChild(h);
        var row = document.createElement('div');
        row.className = 'row';
        row.dataset.group = groupKey;
        grid.appendChild(row);
      }
      var row2 = grid.querySelector('.row[data-group="' + groupKey + '"]');
      row2.appendChild(card(w, lname));
    });
  }

  function card(w, lname) {
    var fig = document.createElement('figure');
    fig.className = 'card';

    var btn = document.createElement('button');
    btn.className = 'thumb';
    btn.type = 'button';
    btn.setAttribute('aria-label', t('card.open'));
    var img = document.createElement('img');
    img.loading = 'lazy';
    img.src = w.file;
    img.alt = t('subject.' + w.subject) + ' — ' + t('grade.' + w.grade) + ' (' + lname + ')';
    btn.appendChild(img);
    btn.addEventListener('click', function () { openLightbox(w, img.alt); });
    fig.appendChild(btn);

    var cap = document.createElement('figcaption');
    var title = document.createElement('span');
    title.className = 'card-grade';
    title.textContent = t('grade.' + w.grade);
    if (w.variant) {
      var badge = document.createElement('span');
      badge.className = 'card-variant';
      badge.textContent = w.variant;
      title.appendChild(document.createTextNode(' '));
      title.appendChild(badge);
    }
    cap.appendChild(title);

    var dls = document.createElement('span');
    dls.className = 'card-dls';
    var pngLink = document.createElement('a');
    pngLink.className = 'card-dl';
    pngLink.href = w.file;
    pngLink.setAttribute('download', '');
    pngLink.textContent = '↓ ' + t('card.png');
    pngLink.setAttribute('aria-label', t('card.downloadPng'));
    pngLink.title = t('card.downloadPng');
    dls.appendChild(pngLink);
    if (w.pdf) {
      var pdfLink = document.createElement('a');
      pdfLink.className = 'card-dl';
      pdfLink.href = w.pdf;
      pdfLink.setAttribute('download', '');
      pdfLink.textContent = '↓ ' + t('card.pdf');
      pdfLink.setAttribute('aria-label', t('card.downloadPdf'));
      pdfLink.title = t('card.downloadPdf');
      dls.appendChild(pdfLink);
    }
    cap.appendChild(dls);

    fig.appendChild(cap);
    return fig;
  }

  // --- Lightbox ---
  function openLightbox(w, alt) {
    var lb = document.getElementById('lightbox');
    var img = document.getElementById('lightbox-img');
    var dlPng = document.getElementById('lightbox-dl-png');
    var dlPdf = document.getElementById('lightbox-dl-pdf');
    img.src = w.file;
    img.alt = alt;
    dlPng.href = w.file;
    dlPng.textContent = '↓ ' + t('card.downloadPng');
    if (w.pdf) {
      dlPdf.href = w.pdf;
      dlPdf.textContent = '↓ ' + t('card.downloadPdf');
      dlPdf.style.display = '';
    } else {
      dlPdf.style.display = 'none';
    }
    lb.classList.add('open');
    lb.setAttribute('aria-hidden', 'false');
    document.getElementById('lightbox-close').focus();
  }
  function closeLightbox() {
    var lb = document.getElementById('lightbox');
    lb.classList.remove('open');
    lb.setAttribute('aria-hidden', 'true');
    document.getElementById('lightbox-img').src = '';
  }

  function init() {
    var bandSel = document.getElementById('filter-band');
    var subjSel = document.getElementById('filter-subject');
    buildFilter(bandSel, M.map(function (w) { return w.band; }), BAND_ORDER, 'filter.all', state.band);
    buildFilter(subjSel, M.map(function (w) { return w.subject; }), SUBJECT_ORDER, 'filter.all', state.subject);
    refreshFilterLabels();

    bandSel.addEventListener('change', function () { state.band = bandSel.value; render(); });
    subjSel.addEventListener('change', function () { state.subject = subjSel.value; render(); });
    document.getElementById('filter-reset').addEventListener('click', function () {
      state.band = 'all'; state.subject = 'all';
      bandSel.value = 'all'; subjSel.value = 'all';
      render();
    });

    // Lightbox wiring.
    document.getElementById('lightbox-close').addEventListener('click', closeLightbox);
    document.getElementById('lightbox').addEventListener('click', function (e) {
      if (e.target.id === 'lightbox') closeLightbox();
    });
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape') closeLightbox();
    });

    // Re-render on language change (updates chrome, filter labels, and cards).
    window.addEventListener('breakout-i18n:changed', function () {
      document.getElementById('filter-reset').textContent = t('filter.reset');
      refreshFilterLabels();
      render();
    });

    render();
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
